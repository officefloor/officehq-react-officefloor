-- Invoices: the owner bills work against a project. Each invoice belongs to one project
-- (project_id references project.id) and carries a monetary amount. Third domain table; a project's
-- detail screen lists its invoices and shows their total.
CREATE TABLE invoice (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT NOT NULL REFERENCES project(id),
    amount     DECIMAL(12, 2) NOT NULL
);
